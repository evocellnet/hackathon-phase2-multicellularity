#!/usr/bin/env python
"""Render results/h9/summary.md from the H9 result tables (no hand-typed numbers).

Inputs: results/h9/{h9_run.json, h9_tests.tsv, h9_transitions.tsv, h9_controls.tsv, h9_seed_stability.tsv}.
"""
import json
import math
import os

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, "results", "h9")


def f(x, d=3):
    return "NA" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def rr(x):
    return f(math.exp(x), 2) if pd.notna(x) else "NA"


def main():
    meta = json.load(open(os.path.join(D, "h9_run.json")))
    tests = pd.read_csv(os.path.join(D, "h9_tests.tsv"), sep="\t").set_index("analysis")
    per = pd.read_csv(os.path.join(D, "h9_transitions.tsv"), sep="\t")
    ctrl = pd.read_csv(os.path.join(D, "h9_controls.tsv"), sep="\t").set_index("control")
    seeds = pd.read_csv(os.path.join(D, "h9_seed_stability.tsv"), sep="\t")
    P = tests.loc["primary"]
    lo, hi = math.exp(P.pooled_ci_low), math.exp(P.pooled_ci_high)
    within = (lo > 1 / 1.5) and (hi < 1.5)
    prim = per[per.set == "primary"].sort_values("r", ascending=False)
    n_excl0 = int(((prim.ci_lo > 0) | (prim.ci_hi < 0)).sum())
    co = ctrl["r_oriented"]
    ds = seeds[seeds.varied == "draw_seed"]["p"]
    os_ = seeds[seeds.varied == "orientation_seed"]
    dic = prim[prim.transition_id == "T_dictyostelia"].iloc[0]
    L = []
    a = L.append
    a("# H9 — genome-wide rate shift at transitions (primary test)\n")
    a(f"Generated by `scripts/phylo/h9_summary.py` from the tables in `results/h9/`; analysis by `scripts/phylo/h9_rates.py` "
      f"(run {meta['finished']}), after PREREG hash verification (`scripts/prereg/check_prereg.py`, tag prereg-v1). "
      "Specification: DESIGN.md §4.6 H9 + v3.1; PREREG.md H9 row (`permute`, controls with two ≥2-tip child clades).\n")
    a("**Statistic.**")
    a(f"- **Per gene:** r_g = log(L̄(P→M tips)/L̄(P→S tips)), with L̄ the equal-split weighted mean path length. Branch lengths come from {meta['n_genes_total']} BUSCO "
      "eukaryota_odb10 markers (IQ-TREE `-te` LG+G4 on the pruned guide tree; taxa with < 50 % site coverage removed per gene).")
    a("- **Path stems:** the D7 path stems (fungal hyphae, volvocine) include every path edge in L̄(P→M).")
    a("- **Gene inclusion:** ≥ 1 outgroup tip, ≥ 2 M tips with MRCA M, ≥ 1 S tip.")
    a(f"- **Per transition:** r_i = median_g r_g; 95 % CI from {meta['n_boot']} gene bootstraps (seed {meta['seed']}).\n")
    a("**Test.**")
    a(f"- **Controls:** the pre-registered pool U from `build_branch_table` (|U| = {meta['U_size']}), restricted to nodes with two child clades of ≥ 2 tips (`h9_control_branches`). This gives "
      f"**{meta['n_pool']} controls**, as assumed by the power table (pool 10); k = {meta['k']}.")
    a("- **Orientation:** control r is oriented at random (`h9_values`, seed 11).")
    a(f"- **Null:** `permute`, {meta['n_draws']:,} draws, seed {meta['seed']}, two-sided.")
    a("- **Effect:** r_i minus the mean oriented control r, pooled by REML.\n")
    a("## Primary result\n")
    a("| test | n | k | T_obs | p | MC SE | min. attainable p | pooled r_i − r̄_controls [95 % CI] | as rate ratio |")
    a("|---|---|---|---|---|---|---|---|---|")
    a(f"| **H9 primary (permute)** | {int(P.n)} | {int(P.k)} | {f(P.T_obs)} | **{f(P.p)}** | {f(P.p_mcse, 4)} | "
      f"{P.min_attainable_p:.1e} | {f(P.pooled_diff)} [{f(P.pooled_ci_low)}, {f(P.pooled_ci_high)}] | "
      f"{rr(P.pooled_diff)} [{f(lo, 2)}, {f(hi, 2)}] |\n")
    a(f"**{'Not significant' if P.p >= 0.05 else 'Significant at 0.05 before Holm'}** (Holm across the 5 primary tests is applied by the PI). "
      + (f"The pooled rate-ratio CI ({f(lo, 2)}, {f(hi, 2)}) lies inside (1/1.5, 1.5), so by the PREREG wording rule this is "
         "\"**no ≥ 1.5-fold genome-wide rate shift**\"." if within else
         f"Inconclusive; compatible with rate ratios [{f(lo, 2)}, {f(hi, 2)}]."))
    a(f"Per transition, the gene-bootstrap CI excludes 0 in {n_excl0} of {len(prim)} stems, in both directions. These are rate differences between two specific "
      f"clades, and the controls differ just as much (oriented control r {f(co.min(), 2)} to {f(co.max(), 2)}).\n")
    a("**Stability across the pre-registered seeds [11, 23, 37, 41, 53].**")
    a(f"- **Permutation draws (Monte Carlo):** p {f(ds.min())}–{f(ds.max())}.")
    a(f"- **Random ± orientation of the {meta['n_pool']} control r values:** p ranges **{f(os_.p.min(), 2)}–{f(os_.p.max(), 2)}** "
      f"(T_obs {f(os_.T_obs.min())}–{f(os_.T_obs.max())}). The H9 p-value therefore depends strongly on this pre-registered randomisation. "
      "With only 10 controls, flipping the sign of one or two large control r values moves the stems' percentiles. Seed 11 is the "
      f"pre-registered result; the conclusion (not significant) holds at every seed (`h9_seed_stability.tsv`).\n")
    a("| transition | P → M (S) | genes | r_i [95 % CI] | rate ratio | u (vs controls) | r_i − r̄_controls | genome-only r_i (genes) |")
    a("|---|---|---|---|---|---|---|---|")
    for _, r in prim.iterrows():
        go = (f"{f(r.r_genome_only)} ({int(r.n_genes_genome_only)})" if pd.notna(r.r_genome_only)
              else f"NA ({int(r.n_genes_genome_only) if pd.notna(r.n_genes_genome_only) else 0} genes)")
        a(f"| {r.transition_id} | {r.P} → {r.M} ({r.S}) | {int(r.n_genes)} | {f(r.r)} [{f(r.ci_lo)}, {f(r.ci_hi)}] | "
          f"{f(r.rate_ratio, 2)} | {f(r.u_percentile, 2)} | {f(r.diff_vs_controls)} | {go} |")
    a(f"\nu = (#controls below + 0.5)/(k + 1); with k = 10 the maximum is {f(10.5 / 11, 2)}. Control 5–95 % range of r − r̄: "
      f"{f(prim.ctrl_pi_low.iloc[0])} to {f(prim.ctrl_pi_high.iloc[0])}.\n")
    a(f"**Dictyostelia caveat.** The largest stem value (r = {f(dic.r)}, rate ratio {f(dic.rate_ratio, 2)}) compares Dictyostelia "
      "(genomes) with its sister Myxogastria_Ceratiomyxa (*Physarum polycephalum*, *Ceratiomyxa fruticulosa*), whose taxa are both "
      "**transcriptomes**. Transcriptome-derived sequences differ in fragmentation, assembly errors and isoform choice, and the S side rests on "
      "2 taxa. In the genome-only rerun the stem cannot be computed at all (no S tip remains), so this value has no "
      "genome-only confirmation.\n")
    a("## Sensitivities (not primary; registry tier `exploratory`, `label=sensitivity`)\n")
    a("| analysis | n | k | T_obs | p | MC SE | pooled rate ratio [95 % CI] |")
    a("|---|---|---|---|---|---|---|")
    for name, r in tests.drop(index="primary").iterrows():
        a(f"| {name} | {int(r.n)} | {int(r.k)} | {f(r.T_obs)} | {f(r.p)} | {f(r.p_mcse, 4)} | {rr(r.pooled_diff)} "
          f"[{rr(r.pooled_ci_low)}, {rr(r.pooled_ci_high)}] |")
    s1 = tests.loc["S1 literal v3 'spec' scheme"]
    a(f"\n- **S1 (`spec`) is not informative.** All N_i are the same {meta['n_pool']} controls. The spec null draws 7 distinct controls "
      f"and can reach at most |T−½| = 0.150, below |T_obs−½| = {f(abs(s1.T_obs - 0.5))}, so p = 1/(N+1) by construction. This is the degenerate "
      "behaviour that D6 replaced, not evidence for an effect.")
    a("- **S2 (genome-only):** transcriptome tips are removed from every gene tree. Dictyostelia drops out (see above), as do the controls whose "
      "sides lose all tips (" + ", ".join(ctrl.index[ctrl.r_genome_only.isna()]) + ").")
    nu = ctrl.index[ctrl.r_unicellular_tips_only.isna()]
    a("- **S3 (control r on unicellular tips only):** multicellular tips inside the control child clades are removed. Controls dropped: "
      + (", ".join(nu) if len(nu) else "none") + ".\n")
    mcx = ctrl[(ctrl.n_mc_tips1 > 0) | (ctrl.n_mc_tips2 > 0)]
    a(f"**Control pool and multicellular content.** The {meta['n_pool']} controls are exactly the pre-registered pool; nothing was substituted. "
      f"Each control branch is unicellular at both ends (in U). In {len(mcx)} of {meta['n_pool']}, however, the child *clades* contain multicellular "
      f"descendants (`h9_controls.tsv`, columns n_mc_tips1/2). Only {meta['n_pool_without_mc_tips']} control has none, so a pool "
      "without them is untestable (≥ 2 controls needed) and would deviate from PREREG. Primary therefore = pre-registered pool with all tips; "
      "the unicellular-tips variant = S3 (confirmed by the PI).\n")
    a("## Descriptive (not tested)\n")
    a("| set | transition | P → M (S) | genes | r_i [95 % CI] | rate ratio | u vs H9 controls |")
    a("|---|---|---|---|---|---|---|")
    for _, r in per[per.set != "primary"].iterrows():
        a(f"| {r.set} | {r.transition_id} | {r.P} → {r.M} ({r.S}) | {int(r.n_genes)} | {f(r.r)} [{f(r.ci_lo)}, {f(r.ci_hi)}] | "
          f"{f(r.rate_ratio, 2)} | {f(r.u_percentile, 2) if pd.notna(r.u_percentile) else '—'} |")
    a("\nThe nested fungal stems compare filamentous clades with yeast sisters (Saccharomycotina, Tremellales), which are known to be fast-evolving, so a negative r is "
      "expected and says nothing about multicellularity. Prokaryotes are descriptive only (|U| = 2).\n")
    a("## Caveats (DESIGN §4.6)")
    a("- **Measure.** r is a *rate shift* over the whole post-P history, not only the stem. Longer generation times bias r below 0.")
    a("- **Relaxed constraint.** \"Relaxed constraint\" may be claimed only with within-protein support (Kr/Kc: `results/krkc/`).")
    a("- **Equal times.** r assumes equal time from P to the M and S tips.")
    a("- **Low single-copy coverage.** Species with > 50 % duplicated BUSCOs contribute few single-copy markers (`results/qc/flags.tsv`).\n")
    a("## Files")
    a("- **Per-transition and per-control tables:** `h9_transitions.tsv`, `h9_controls.tsv`.")
    a("- **Test results:** `h9_tests.tsv` and `h9_seed_stability.tsv`.")
    a("- **Per unit × gene tables:** `h9_gene_table.tsv`, `h9_gene_table_genome_only.tsv` and `h9_gene_table_prok.tsv`.")
    a("- **Registry:** `results/analysis_registry.tsv` rows with hypothesis H9.")
    with open(os.path.join(D, "summary.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
