#!/usr/bin/env python
"""Render results/rer/summary.md from the RER outputs, and evaluate both consistency criteria.

Criterion A (first used): >= 4 transitions with clade-mean RER beyond ±0.5 in one direction (opposite-
direction transitions allowed). Criterion B (adopted after seeing that every A-gene also had
opposite-direction transitions): as A, but no transition beyond 0.5 in the opposite direction.
Both are calibrated on the same 1,000 permuted clade placements (seed 11); both are reported.
"""
import json
import math
import os
import sys
import warnings

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts", "phylo"))
from mcell import rates, branchstats as bs  # noqa: E402
import h9_rates as H  # noqa: E402
import rer_busco as R  # noqa: E402

D = os.path.join(ROOT, "results", "rer")


def f(x, d=3):
    return "NA" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def crit(cm, kind):
    up = np.nansum(cm >= R.THR, axis=1)
    dn = np.nansum(cm <= -R.THR, axis=1)
    if kind == "A":
        return (up >= R.MIN_T) | (dn >= R.MIN_T)
    return ((up >= R.MIN_T) & (dn == 0)) | ((dn >= R.MIN_T) & (up == 0))


def main():
    warnings.simplefilter("ignore")
    meta = json.load(open(os.path.join(D, "rer_run.json")))
    genes = pd.read_csv(os.path.join(D, "rer_genes.tsv"), sep="\t", index_col=0)
    cm = pd.read_csv(os.path.join(D, "rer_clade_means.tsv"), sep="\t", index_col=0)
    rer = pd.read_csv(os.path.join(D, "rer_matrix.tsv"), sep="\t", index_col=0)
    tree = bs.load_tree(os.path.join(ROOT, "data", "guide_tree_euk.nwk"))
    roots = list(meta["clade_roots"].keys())
    perm = rates.permuted_clade_roots(tree, roots, n_perm=1000, seed=R.SEED)
    rows = []
    for kind in ("A", "B"):
        obs = crit(cm.to_numpy(), kind)
        null = np.array([crit(rates.clade_mean_rer(rer, tree, pr).to_numpy(), kind).sum() for pr in perm])
        p = (1 + (null >= obs.sum()).sum()) / (1 + len(null))
        rows.append(dict(criterion=kind, observed=int(obs.sum()), null_mean=null.mean(), null_q95=np.quantile(null, .95),
                         p=p, genes=";".join(cm.index[obs])))
    ct = pd.DataFrame(rows)
    ct.to_csv(os.path.join(D, "rer_consistency_criteria.tsv"), sep="\t", index=False, float_format="%.4g")
    A = ct.iloc[0]
    reg_path = H.REG
    done_flag = os.path.join(D, ".criterionA_registered")
    if not os.path.exists(done_flag):
        bs.append_registry(reg_path, dict(
            hypothesis="Q5 gene-level RER consistency (>=4 transitions), criterion A", statistic="n genes with >=4 "
            "transitions of same-sign clade-mean RER |.|>=0.5 (opposite allowed); null = permuted clade placements",
            n=int(genes.p_perm.notna().sum()), k=len(roots), estimate=int(A.observed), ci_low="NA", ci_high="NA",
            p=float(A.p), p_mcse="NA", holm_p="NA", tier="exploratory", seed=R.SEED, n_draws=1000,
            scheme="clade-placement permulation",
            input_md5s=[os.path.join(ROOT, "runs/phylo/euk/genetrees/branch_lengths.tsv")],
            notes="label=exploratory; first criterion used; superseded by criterion B after inspection (A-genes all "
                  f"had opposite-direction transitions); null mean {A.null_mean:.2f}"))
        open(done_flag, "w").write("1\n")
    desc = genes["description"]
    t = genes.dropna(subset=["p_perm"])
    L = []
    a = L.append
    a("# Gene-level relative evolutionary rates (RER), 250 BUSCO markers — EXPLORATORY\n")
    a("Generated by `scripts/phylo/rer_summary.py` from the outputs of `scripts/phylo/rer_busco.py` (module `mcell/rates.py`; "
      "simulation tests in `tests/test_rates.py`).\n")
    a("**Method.** A RERconverge-style re-implementation:")
    a(f"- **Input.** Per-gene IQ-TREE `-te` branch lengths, ≥ {meta['min_sp']} species per gene.")
    a("- **Normalisation.** Branch lengths are projected on a robust (median) genome-wide branch-length vector, with a square-root transform and mean–variance weighting.")
    a("- **Branch sets.**")
    a(f"  - *Foreground* ({meta['n_fg_edges']} edges): the 7 primary transitions — stem edges (incl. D7 path edges) plus "
      "multicellular crown edges (within_multicellular, nested stems).")
    a(f"  - *Excluded* ({meta['n_excluded_edges']} edges): reversals/unicellular lineages inside those clades (yeasts, *Allomyces*, "
      "Tetrabaena stem) and every non-unicellular edge elsewhere (exploratory multicellular lineages, grey zones).")
    a(f"  - *Background* ({meta['n_bg_edges']} edges): within-unicellular edges.")
    a(f"- **Statistic and null.** Kendall τ_b per gene. The null is a permulation by random clade placement matched on tip count ({meta['n_perm']} permutations, seed 11; "
      "excluded edges stay excluded); p is two-sided, and BH-FDR is applied across genes with ≥ 2 transitions represented.\n")
    a("## Results\n")
    a(f"- **Tests.** {meta['n_genes_tested']} genes tested. p < 0.05: {meta['n_p05']} (expected under the null {meta['expected_p05']:.1f}); "
      f"**q < 0.10: {meta['n_q10']}**; q < 0.05: {meta['n_q05']}. No gene has a foreground rate shift that survives FDR.")
    a(f"- **Calibration.** The excess of small p-values (lowest decile {int((t.p_perm < 0.1).sum())} vs {0.1 * len(t):.0f} expected) is modest. It is "
      "compatible either with weak diffuse signal or with residual miscalibration of the clade-placement null on the real tree. We cannot "
      "distinguish the two here.")
    a(f"- **Direction.** Mean τ = {f(t.tau.mean())}; {f((t.tau > 0).mean() * 100, 0)} % of genes have τ > 0. By construction RER removes genome-wide shifts, "
      "so this says nothing about H9.\n")
    a("**Top 15 genes by permulation p** (exploratory; none significant after BH):\n")
    a("| BUSCO marker | OrthoDB / BUSCO description | τ_b | p (perm.) | q (BH) | transitions represented |")
    a("|---|---|---|---|---|---|")
    for g, r in t.sort_values("p_perm").head(15).iterrows():
        a(f"| {g} | {desc.get(g, '')} | {f(r.tau)} | {f(r.p_perm, 4)} | {f(r.q_bh)} | {int(r.n_transitions)} |")
    a("\n**Consistency across ≥ 4 transitions.** For each gene and transition, we take the mean RER over that clade's foreground edges, "
      "and count transitions beyond ±0.5:\n")
    a("| criterion | rule | genes observed | null mean (95th pct) | p |")
    a("|---|---|---|---|---|")
    rule = {"A": "≥ 4 transitions in one direction (opposite allowed)", "B": "≥ 4 in one direction, none ≥ 0.5 in the opposite"}
    for _, r in ct.iterrows():
        a(f"| {r.criterion} | {rule[r.criterion]} | {int(r.observed)} | {f(r.null_mean, 2)} ({f(r.null_q95, 0)}) | {f(r.p)} |")
    a("")
    a_genes = ", ".join(f"{g} ({desc.get(g, '')})" for g in str(A.genes).split(";") if g)
    a(f"Criterion A was used first. Its {int(A.observed)} genes ({a_genes}) "
      "each also shift in the opposite direction in 1–2 other transitions, so they are not *consistent* shifts. Criterion B was adopted after "
      "seeing this (post hoc, stated here) and finds no gene. **Conclusion: no gene shifts consistently across ≥ 4 of the 7 "
      "transitions.**\n")
    a("**Caveats.**")
    a("- **Marker set.** BUSCO markers are conserved housekeeping genes, chosen for being single-copy, which is a poor set for lineage-specific rate shifts. The planned "
      "HOG-based RER (≤ 1,000 near-single-copy HOGs) needs the eukaryote Ancestra output.")
    a("- **Permulation scheme.** The clade-placement permulation is not Saputra et al.'s BM-simulation permulation (see `results/phylo/notes.md`).\n")
    a("Files: `rer_genes.tsv` (all genes), `rer_clade_means.tsv`, `rer_matrix.tsv`, `rer_consistency_criteria.tsv`, `rer_run.json`.")
    with open(os.path.join(D, "summary.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
