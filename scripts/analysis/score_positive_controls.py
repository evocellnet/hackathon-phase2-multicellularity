#!/usr/bin/env python
"""Score the pre-registered positive controls (data/positive_controls.tsv) on one Ancestra run.

    python scripts/analysis/score_positive_controls.py --run {euk,prok}

Rules: mcell/controls.py (one function per control; terms of data/prereg_definitions.tsv; node mapping and
pi_resolution of data/positive_controls_nodes.tsv). Needs runs/analysis/<run>/ (build_branch_events.py). Uses the
gain ladder (results/gainladder/<run>/, runs/gainladder/<run>/per_query.parquet) when present; rules that need it
are 'undetermined' otherwise -- re-run when it exists (the script is idempotent; outputs are overwritten).
Pfam: pre-registered HMM subset (data/annotations/pfam_prereg/<run>; covers every Pfam the rules use).
Outputs results/positive_controls/<run>/controls.tsv and summary.md (+ one registry row).
"""
import argparse
import datetime as dt
import os
import sys
import warnings

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts", "prereg"))

import pandas as pd  # noqa: E402

from mcell import analysis as an  # noqa: E402
from mcell import branchstats as bs  # noqa: E402
from mcell import controls as pc  # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run", required=True, choices=["euk", "prok"])
    ap.add_argument("--out", default=None)
    ap.add_argument("--registry", default=os.path.join(ROOT, "results", "analysis_registry.tsv"))
    a = ap.parse_args(argv)
    import check_prereg
    if not check_prereg.verify(strict=False):
        sys.exit("PREREG hash mismatch: aborting")
    p = an.run_paths(a.run)
    cache = an.load_cache(a.run, p)
    tr, traits, tree, bt = an.load_setup(a.run, p)
    lg = pq = None
    if os.path.exists(p["ladder_gains"]):
        lg = pd.read_csv(p["ladder_gains"], sep="\t")
    if os.path.exists(p["ladder_per_query"]):
        pq = pd.read_parquet(p["ladder_per_query"])
    ctx = pc.Ctx(cache=cache, species=pd.read_csv(p["species"], sep="\t"), transitions=tr, paths=p,
                 ladder_gains=lg, ladder_per_query=pq, bt=bt)
    ctrl = pd.read_csv(os.path.join(ROOT, "data", "positive_controls.tsv"), sep="\t")
    ctrl = ctrl[ctrl["run"] == a.run]
    nodes = pd.read_csv(os.path.join(ROOT, "data", "positive_controls_nodes.tsv"), sep="\t").set_index("control_id")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = pc.score_all(ctx, ctrl, pc.EUK_RULES if a.run == "euk" else pc.PROK_RULES)
    res["pi_resolution"] = res["control"].map(nodes["pi_resolution"]).fillna("")
    out = a.out or os.path.join(ROOT, "results", "positive_controls", a.run)
    os.makedirs(out, exist_ok=True)
    res.to_csv(os.path.join(out, "controls.tsv"), sep="\t", index=False)
    n = len(res)
    nyes = int((res["recovered"] == "yes").sum())
    und = res.loc[res["recovered"] == "undetermined", "control"].tolist()
    hi_fail = res[(res["confidence"] == "high") & (res["recovered"].isin(["no", "not_evaluable"]))]["control"].tolist()
    L = [f"# Positive controls: {a.run} run", "",
         f"Generated by `scripts/analysis/score_positive_controls.py --run {a.run}` on {dt.date.today()}. "
         f"Gain ladder: {'available' if lg is not None else 'NOT available'}. Pfam: pre-registered subset.", "",
         f"Recovered: **{nyes}/{n}**; not recovered: {int((res['recovered'] == 'no').sum())}; not_evaluable: "
         f"{int((res['recovered'] == 'not_evaluable').sum())}; undetermined (input missing): {len(und)} {und if und else ''}.", ""]
    if a.run == "euk":
        L += [f"Pre-registered pass criterion (PREREG.md): >= 11 of 16 eukaryotic controls recovered and every "
              f"high-confidence failure explained. Count part: {nyes}/16 -> {'met' if nyes >= 11 else 'NOT met'}"
              + (" (provisional: undetermined controls remain)" if und else "") + ". High-confidence failures needing an "
              f"explanation: {', '.join(hi_fail) if hi_fail else 'none'}.", ""]
    L += ["| control | confidence | expected | recovered | observed | notes |", "|---|---|---|---|---|---|"]
    for _, r in res.iterrows():
        L.append(f"| {r['control']} | {r['confidence']} | {r['expected']} | **{r['recovered']}** | {r['observed']} | "
                 f"{r['notes']} |")
    open(os.path.join(out, "summary.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L[:8]))
    bs.append_registry(a.registry, dict(
        hypothesis="positive_controls", statistic=f"number of {a.run} positive controls recovered (pass_rule)",
        n=n, estimate=nyes, p="NA", p_mcse="NA", holm_p="NA", tier="exploratory", scheme="none",
        input_md5s=[os.path.join(ROOT, "data", f) for f in ("positive_controls.tsv", "positive_controls_nodes.tsv",
                                                           "prereg_definitions.tsv")],
        notes=f"{a.run}; " + "; ".join(f"{c}={r}" for c, r in zip(res["control"], res["recovered"]))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
