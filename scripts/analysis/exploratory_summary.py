#!/usr/bin/env python
"""Collect the summary.json files of the EXPLORATORY analyses into results/exploratory/<run>/summary.md
(numbers only, no interpretation).

    python scripts/analysis/exploratory_summary.py --run {euk,prok}
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def f(x, nd=3):
    if x is None:
        return "NA"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        if not math.isfinite(x):
            return "NA"
        if x != 0 and (abs(x) < 1e-3 or abs(x) >= 1e5):
            return f"{x:.2e}"
        return f"{x:.{nd}g}" if abs(x) < 1 else f"{x:.{nd + 1}g}"
    return str(x)


def table(rows, cols, head=None):
    if not rows:
        return ["(none)", ""]
    out = ["| " + " | ".join(head or cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(("<1e-300" if (c.startswith(("p", "q")) and r.get(c) == 0) else f(r.get(c)))
                                     for c in cols) + " |")
    out.append("")
    return out


def load(run, name):
    p = os.path.join(ROOT, "results", "exploratory", run, name, "summary.json")
    return json.load(open(p)) if os.path.exists(p) else None


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, choices=["euk", "prok"])
    a = ap.parse_args(argv)
    L = [f"# Exploratory analyses: {a.run} ({'DRY RUN, descriptive' if a.run == 'prok' else 'EXPLORATORY'})", "",
         "All numbers below are EXPLORATORY or descriptive (not part of the primary Holm family). "
         "Generated by scripts/analysis/exploratory_summary.py from results/exploratory/"
         f"{a.run}/*/summary.json; full tables in the same folders. Commands: results/README_run_exploratory.md.", ""]
    pw = load(a.run, "pfam_wide")
    if pw:
        L += ["## 1. Pfam-wide (pfam_wide.py)", "",
              f"Species with full Pfam: {pw['n_pfam_annotated']}/{pw['n_species']}; domains observed: "
              f"{pw['n_domains_total']}; control pool: {pw['pool']} (n = {pw['n_pool']}); evaluable: "
              f"{pw.get('n_evaluable_transitions')} transitions, {pw.get('n_evaluable_controls')} controls.", ""]
        L += table(pw["per_transition"], ["transition", "n_M_annot", "n_S_annot", "n_domains", "n_tested_mwu",
                                          "n_expanded", "n_expanded_by_test", "n_gained", "n_contracted", "n_lost",
                                          "n_hog_expanded", "n_both"])
        L += [f"Mean per control pseudo-transition: {pw['control_flag_means']}", "",
              "Convergence (k = number of transitions flagged; permute = transitions + controls exchangeable, "
              "matched = matched controls only, sensitivity):", ""]
        L += table(pw["convergence_global"], ["flag", "k_min", "scheme", "n_domains_obs", "null_mean", "null_q95",
                                              "p_perm"])
        L += ["Top domains, expanded-or-gained:", ""]
        L += table(pw["top_convergent"], ["pfam_acc", "pfam_name", "k_obs", "k_null_mean", "p_perm", "q", "transitions"])
        L += ["Top domains, lost:", ""]
        L += table(pw["top_lost"], ["pfam_acc", "pfam_name", "k_obs", "k_null_mean", "p_perm", "q", "transitions"])
    co = load(a.run, "cooption")
    if co:
        L += ["## 2. Co-option index (cooption.py; descriptive)", "", f"Notes: {co['notes']}; pool: {co['pool']}", ""]
        L += table(co["per_transition"], ["version", "transition", "n_F", "n_P", "C", "C_Pparent", "k_controls",
                                          "median_C_controls", "C_minus_median", "u"])
        L += table([dict(version=k, **v) for k, v in co["versions"].items()],
                   ["version", "n", "mean_C", "mean_diff", "T_mean_u"])
    ar = load(a.run, "architectures")
    if ar:
        L += ["## 3. New Pfam architectures (architectures.py; H11)", "",
              f"Species with full Pfam: {ar['n_annotated']}/{ar['n_species']}; architectures: {ar['n_architectures']} "
              f"({ar['n_multi']} multi-domain; {ar['n_new_multi_any_branch']} multi-domain with an origin branch); "
              f"pool: {ar['pool']} (n = {ar['n_pool']}); pool means: {ar['pool_mean']}", ""]
        L += table([dict(transition=t, **v) for t, v in ar["stems"].items()],
                   ["transition", "branch", "new_arch_all", "new_arch_multi", "new_arch_recombined"])
        L += table(ar["tests"], ["statistic", "version", "n", "k", "T_obs", "p", "min_attainable_p", "pooled_log_OE",
                                 "ci_low", "ci_high", "q_bh"])
    pt = load(a.run, "protein_traits")
    if pt:
        L += ["## 4. Protein traits (protein_traits.py; H9 companion, H10)", "",
              f"Disorder available for {pt['n_disorder_species']}/{pt['n_species']} species.", ""]
        rows = [r for r in pt["tests"] if r.get("p") is not None]
        L += table(rows, ["transition", "test", "subset", "n", "hl", "hl_lo", "hl_hi", "p", "q_bh", "u_vs_controls",
                          "median_hl_controls"])
        L += ["Tests without data (n = 0 or no p): " + str(sorted({f"{r['test']}/{r['subset']}" for r in pt["tests"]
                                                                  if r.get("p") is None})), ""]
        L += table(pt["across"], ["test", "subset", "n_transitions", "n_positive", "median_hl"])
    rv = load(a.run, "reversals")
    if rv:
        L += ["## 5. Reversals (reversals.py)", ""]
        if not rv.get("tests"):
            L += [f"n reversals: {rv.get('n_reversals', 0)}. {rv.get('note', '')}", ""]
        else:
            L += table([r for r in rv["tests"] if r["role"] == "reversal"],
                       ["reversal", "branch_child", "rev_parent", "preceding", "group", "a_lost", "b_kept", "c_bg_lost",
                        "d_bg_kept", "odds_ratio", "or_lo", "or_hi", "p_greater", "q_bh", "ratio_of_or_vs_sisters"])
            L += ["Sister controls (gained_or_dup):", ""]
            L += table([r for r in rv["tests"] if r["role"] == "sister_control" and r["group"] == "gained_or_dup"],
                       ["reversal", "branch_child", "child_state", "odds_ratio", "or_lo", "or_hi", "p_greater"])
    out = os.path.join(ROOT, "results", "exploratory", a.run, "summary.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
