#!/usr/bin/env python3
"""Step 7: write DATA.md (dataset provenance) from the manifest and final tables. Re-runnable."""
import os, datetime
import pandas as pd

P = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def rd(p):
    return open(f'{P}/{p}').read().split()[0] if os.path.exists(f'{P}/{p}') else 'n/a'


def main():
    man = pd.read_csv(f'{P}/data/raw/download_manifest.tsv', sep='\t', dtype=str)
    e = pd.read_csv(f'{P}/data/species_final.tsv', sep='\t', dtype=str)
    k = pd.read_csv(f'{P}/data/species_final_prok.tsv', sep='\t', dtype=str)
    allsp = pd.concat([e.assign(kingdom='euk'), k.assign(kingdom='prok')])
    sel = set(allsp['code'])
    man = man[man['code'].isin(sel)]
    up = man[man['source'].str.startswith('UniProt') & man['url'].str.endswith('.fasta.gz')]
    nc = man[man['source'].str.startswith('NCBI')]
    by = allsp.groupby(['kingdom', 'source_db']).agg(n=('code', 'size'),
                                                     proteins=('n_proteins_final', lambda x: int(x.astype(int).sum())))
    L = []
    w = L.append
    w('# DATA — datasets, versions, checksums, licences')
    w('')
    w(f'Generated by `scripts/data/write_data_md.py` on {datetime.date.today().isoformat()}. '
      'Nothing under `data/raw/` or `data/proteomes/` is committed (both are git-ignored); everything there is '
      're-created by `scripts/data/run_all.sh`. Per-species provenance (source accession, raw file, processing, '
      'md5 of the final FASTA, protein counts, BUSCO) is in **`data/species_final.tsv`** and '
      '**`data/species_final_prok.tsv`**; per-file download URLs, dates and md5s are in '
      '`data/raw/download_manifest.tsv` (git-ignored; regenerated by `fetch_proteomes.py`).')
    w('')
    w('## Summary of the final proteome set')
    w('')
    w('| kingdom | source | species | proteins (final) |')
    w('|---|---|---|---|')
    for (kg, db), r in by.iterrows():
        w(f'| {kg} | {db} | {r.n} | {r.proteins:,} |')
    for kg, d in (('euk', e), ('prok', k)):
        w(f'| **{kg} total** | | **{len(d)}** | **{int(d.n_proteins_final.astype(int).sum()):,}** |')
    w('')
    w('## Datasets')
    w('')
    w('| dataset | version | source URL | downloaded | checksum (md5) | licence | used for |')
    w('|---|---|---|---|---|---|---|')
    w(f'| UniProtKB reference proteomes | release 2026_03 (relnotes checked at download; per-proteome files only '
      f'exist for the current release) | `https://ftp.uniprot.org/pub/databases/uniprot/current_release/knowledgebase/'
      f'reference_proteomes/<Eukaryota|Bacteria|Archaea>/<UP>/<UP>_<taxid>.fasta.gz` (+ `.gene2acc.gz`) | '
      f'{",".join(sorted(set(up.date)))} | per file in `download_manifest.tsv` ({len(up)} FASTA files) | CC BY 4.0 | '
      f'{len(up)} proteomes (canonical, gene-centric) |')
    w(f'| EukProt | v3 (2021_11_22), Richter et al. 2022 PCJ | https://ndownloader.figshare.com/files/34434377 '
      f'(figshare 10.6084/m9.figshare.12417881.v3) | 2026-10-28 | `EukProt_proteins.v03.2021_11_22.tgz` '
      f'{rd("data/raw/eukprot/EukProt_proteins.md5")} | CC BY 4.0 (original data-source terms apply) | '
      f'{int((allsp.source_db == "EukProt").sum())} proteomes; metadata + BUSCO tables from github.com/beaplab/EukProt |')
    w(f'| LukProt | v1.5.1.rev2, Sobala 2024 GBE | https://zenodo.org/records/13829058 '
      f'(`LukProt_v1.5.1_single_species_FASTA.7z`) | 2026-10-28 | {rd("data/raw/lukprot/LukProt_single_species_FASTA.md5")} '
      f'(matches Zenodo) | CC BY 4.0 | {int((allsp.source_db == "LukProt").sum())} proteomes (LP00007, LP00010, LP00014, LP00201) |')
    w(f'| NCBI Datasets (GenBank/RefSeq annotations) | assemblies listed below | '
      f'`https://api.ncbi.nlm.nih.gov/datasets/v2/genome/accession/<acc>/download?include_annotation_type=PROT_FASTA&'
      f'include_annotation_type=GENOME_GFF` | {",".join(sorted(set(nc.date)))} | per zip in `download_manifest.tsv` | '
      f'INSDC, no use restrictions (cite submitters) | {len(nc)} proteomes (longest protein per gene from GFF) |')
    w(f'| NCBI taxonomy taxdump | snapshot of 2026-10-28 | https://ftp.ncbi.nlm.nih.gov/pub/taxonomy/taxdump.tar.gz | '
      f'2026-10-28 | {rd("data/raw/taxdump/taxdump.tar.gz.md5")} | public domain (NCBI) | guide trees |')
    w('| Pfam | 38.2 (2026-01; based on UniProtKB 2025_03; 30,134 Pfam-A families) | '
      'https://ftp.ebi.ac.uk/pub/databases/Pfam/releases/Pfam38.2/ | 2026-10-28 | Pfam-A.hmm.gz 7ab3c4e215d0daaea3004e37c4e24f8a; '
      'Pfam-A.clans.tsv.gz a70eeffcd8105ff094ea5834456d8bab (all in `data/raw/pfam/md5_checksums`) | CC0 | domain annotation |')
    w('| BUSCO lineages | eukaryota_odb10, bacteria_odb10, archaea_odb10 (all 2024-01-08; OrthoDB 10.1) | '
      'https://busco-data.ezlab.org/v5/data/lineages/ | 2026-10-28 | eukaryota 93e2a6ec05708dbf0f23db078b88c5a8, '
      'bacteria bff9523df89980699c01e8f31e490496, archaea 3eb26c670c520c0f3b32bff46fce03d7 (`file_versions.tsv`) | '
      'CC BY-ND 4.0 (OrthoDB/BUSCO datasets) | completeness QC with BUSCO 6.1.0 (protein mode, offline) |')
    w('')
    w('## NCBI assemblies used')
    w('')
    w('| code | species | accession | md5 of downloaded package |')
    w('|---|---|---|---|')
    sp = allsp.set_index('code')
    for _, r in nc.sort_values('code').iterrows():
        w(f'| {r.code} | {sp.loc[r.code, "species"]} | {r.source.split(":")[1]} | {r.md5} |')
    w('')
    w('## Processing (summary; details in `scripts/data/` and `data/guide_tree_edits.md`)')
    w('')
    w('- One protein per gene: UniProt canonical FASTA (+ gene2acc group collapse); NCBI longest protein per GFF gene; '
      'EukProt/LukProt genome sets longest protein per parsed gene ID (isoforms present in e.g. Sycon, Chromera, Cyanophora); '
      'transcriptomes longest ORF per Trinity/SOAP gene where headers allow, then `cd-hit -c 0.95 -G 0 -aS 0.9 -n 5`.')
    w('- Cleaning: terminal `*` trimmed, internal stops / non-standard letters -> X, length >= 50 aa, exact duplicate '
      'sequences removed within species. IDs `<code>_<original id>` (characters outside [A-Za-z0-9_.-] -> `_`); '
      'mapping tables in `data/proteomes/idmaps/<code>.tsv.gz`.')
    w('- QC: BUSCO 6.1.0 protein mode with the odb10 lineages above; `low_quality = 1` if C < 50 %; '
      '`flag_DF15 = 1` for transcriptome-derived sets with D or F > 15 %.')
    cap = pd.read_csv(f'{P}/data/species_cap_drops.tsv', sep='\t')
    w('')
    w('## Eukaryote protein cap (PI rule, 2026-10-28)')
    w('')
    w('Hard cap: **3.0 M eukaryote proteins** (Ancestra peak memory within the 150 GB allocation). Written rule, applied by '
      '`apply_cap()` in `scripts/data/select_final.py` after preprocessing: drop taxa in order (1) tier = optional AND '
      'role = background, largest number of final proteins first; (2) then other optional taxa, largest first, only if '
      'every transition side they are on keeps >= 2 species; never drop the only representative of a transition side. '
      f'Stop as soon as the total <= 3.0 M. Result: {len(cap)} taxa dropped, total '
      f'{int(e.n_proteins_final.astype(int).sum()):,} proteins in {len(e)} eukaryotes (`data/species_cap_drops.tsv`).')
    w('')
    w('| species | code | proteins | rule step | total after |')
    w('|---|---|---|---|---|')
    for _, r in cap.iterrows():
        w(f'| {r.species} | {r.code} | {r.n_proteins_final:,} | {r.rule_step} | {r.total_after:,} |')
    w('')
    lq = allsp[allsp.low_quality.astype(int) == 1]
    w('## QC flags')
    w('')
    w('BUSCO 6.1.0 (odb10, protein mode, offline); full outputs incl. single-copy marker sequences in '
      '`data/busco_runs/<code>/`. Low quality (C < 50 %, kept, `low_quality = 1`): '
      + ', '.join(f'{r.code} ({r.species}, C={r.busco_C})' for _, r in lq.iterrows()) + '.')
    df = allsp[allsp.get('flag_DF15', pd.Series(dtype=str)).astype(str) == '1']
    w('Transcriptome-derived sets with BUSCO D or F > 15 % (`flag_DF15 = 1`): '
      + ', '.join(f'{r.code} (D={r.busco_D}, F={r.busco_F})' for _, r in df.iterrows()) + '.')
    w('')
    w('Note: during the first BUSCO pass (13:06 on 2026-10-28) files inside the shared lineage directories were deleted '
      'by an unknown process (archaea_odb10 emptied, eukaryota_odb10/prfl missing), so 51 runs failed. The three '
      'lineages were re-downloaded, verified against the md5s above, replaced and made read-only; the failed runs were '
      'repeated. The damaged copies are kept in `data/raw/busco/corrupt_*`.')
    open(f'{P}/DATA.md', 'w').write('\n'.join(L) + '\n')
    print('wrote DATA.md')


if __name__ == '__main__':
    main()
