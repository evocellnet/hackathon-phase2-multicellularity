#!/usr/bin/env python3
"""Write data/dense/STATUS.txt (per-panel readiness) and the round-2 dense-dataset section of DATA.md
(between the markers <!-- DENSE START --> / <!-- DENSE END -->; regenerated, idempotent).
Usage: report.py [--ready R2 R4 ...]   (panels listed as ready are marked READY in STATUS.txt)"""
import argparse, datetime, glob, os, subprocess
import pandas as pd

P = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ORDER = ['R2', 'R4', 'R3', 'R6', 'R5', 'R1', 'R8', 'R7']
TITLES = {'R1': 'Holozoa', 'R2': 'Fungi', 'R3': 'Streptophyta', 'R4': 'Volvocales', 'R5': 'Rhodophyta',
          'R6': 'Stramenopiles / Phaeophyceae', 'R7': 'Amoebozoa', 'R8': 'Cyanobacteria'}
LIC = {'UniProt': 'CC BY 4.0', 'NCBI': 'INSDC (no restrictions; cite submitters)', 'EukProt': 'CC BY 4.0 (EukProt v3)',
       'LukProt': 'CC BY 4.0 (LukProt v1.5.1)',
       'AUGUSTUS': 'gene models predicted here (AUGUSTUS 3.5.0, chlamy2011) on an INSDC assembly (no restrictions)'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ready', nargs='*', default=[])
    ap.add_argument('--note', nargs='*', default=[], help='free-text lines appended to STATUS.txt')
    a = ap.parse_args()
    now = subprocess.run(['date', '+%Y-%m-%d %H:%M %Z'], capture_output=True, text=True).stdout.strip()
    st = [f'DENSE PANEL STATUS (round 2) - updated {now}', '',
          'Each READY panel has: data/dense/<R>/proteomes/<code>.fa (symlinks), species.tsv, guide_tree.nwk '
          '(leaves = file stems, unique internal names), tree_edits.md, transitions.tsv.',
          'Ancestra input: proteome directory data/dense/<R>/proteomes/ + species tree data/dense/<R>/guide_tree.nwk', '']
    md = ['<!-- DENSE START -->', '## Round-2 dense per-event panels (data/dense/)', '',
          f'Generated by `scripts/dense/report.py` ({now}). Built by `scripts/dense/build_panel.py <R>` from the curated '
          'specs `scripts/dense/specs/<R>.tsv` and `scripts/dense/panels.py`. Species already in round 1 reuse the '
          'round-1 files (symlinks); new proteomes are processed with the round-1 code (`scripts/data/preprocess_proteomes.py`: '
          'one protein per gene, >= 50 aa, IDs `<code>_<id>`, CD-HIT 0.95 for transcriptomes) into `data/proteomes/dense/` '
          '(git-ignored). BUSCO 6.1.0 protein mode (eukaryota_odb10 / bacteria_odb10, as round 1) in '
          '`data/dense/busco_summary_dense.tsv`. Raw downloads: `data/dense/download_manifest_dense.tsv` (URL, md5, date). '
          'NCBI genome reports were queried through the Datasets `v2alpha` endpoint because `v2` returned HTTP 500 on 2026-10-29 '
          '(downloads use `v2`).', '',
          '| panel | species | proteins | genomes | transcriptomes | BUSCO C<70 | unicellular/simple/complex | events |',
          '|---|---|---|---|---|---|---|---|']
    new_rows = []
    for R in ORDER:
        f = f'{P}/data/dense/{R}/species.tsv'
        if not os.path.exists(f):
            st.append(f'{R} {TITLES[R]}: NOT STARTED'); continue
        s = pd.read_csv(f, sep='\t', dtype=str).fillna('')
        tr = pd.read_csv(f'{P}/data/dense/{R}/transitions.tsv', sep='\t', dtype=str).fillna('')
        n = s['n_proteins'].astype(int).sum(); res = s['n_residues'].astype(int).sum()
        g = (s['data_type'] == 'genome').sum(); tx = len(s) - g
        low = s['flags'].str.contains('BUSCO_C<70').sum()
        sc = s['mc_state'].value_counts()
        states = f"{sc.get('unicellular', 0)}/{sc.get('simple', 0)}/{sc.get('complex', 0)}"
        kinds = tr['kind'].value_counts().to_dict()
        status = 'READY' if R in a.ready else 'BUILT (not yet released)'
        st += [f'{R} {TITLES[R]}: {status}',
               f'   species={len(s)} proteins={n:,} residues={res:,} genomes={g} non-genome={tx} BUSCO_C<70={low}',
               f'   states uni/simple/complex={states}; events={len(tr)} {kinds}',
               f'   non-genome: ' + (', '.join(f"{c} ({d})" for c, d in zip(s['code'], s['data_type']) if d != 'genome') or 'none'),
               f'   BUSCO C<70: ' + (', '.join(f"{c} ({b})" for c, b, fl in zip(s['code'], s['busco_C'], s['flags']) if 'BUSCO_C<70' in fl) or 'none'),
               '']
        md.append(f'| {R} {TITLES[R]} | {len(s)} | {n:,} | {g} | {tx} | {low} | {states} | {len(tr)} |')
        for _, r in s.iterrows():
            if 'round-1 file' in r['source']:
                continue
            new_rows.append((R, r))
    md += ['', '### New proteomes (not in round 1)', '',
           '| panel | code | species | source | data type | md5 of final FASTA | licence |', '|---|---|---|---|---|---|---|']
    seen = set()
    for R, r in new_rows:
        if r['code'] in seen:
            continue
        seen.add(r['code'])
        db = r['source'].split(':')[0]
        md.append(f"| {R} | {r['code']} | {r['species']} | {r['source']} | {r['data_type']} | {r['md5']} | {LIC.get(db, '?')} |")
    md += ['', 'Dataset versions as in the table above: UniProt 2026_03, EukProt v3, LukProt v1.5.1.rev2 (fully extracted '
           'from `LukProt_v1.5.1_single_species_FASTA.7z`, md5 57f80efc4d9eef5cef3156cf305bed11), NCBI assemblies by accession. '
           'EukaryOMA (All.Oct2026) API serves sequences only one protein per request, so it was not used as a sequence '
           'source (its genomes come from the same primary sources).', '<!-- DENSE END -->']
    st += ['NOTES:'] + [f'- {x}' for x in a.note] if a.note else []
    open(f'{P}/data/dense/STATUS.txt', 'w').write('\n'.join(st) + '\n')
    dm = open(f'{P}/DATA.md').read()
    block = '\n'.join(md) + '\n'
    if '<!-- DENSE START -->' in dm:
        pre = dm.split('<!-- DENSE START -->')[0]
        post = dm.split('<!-- DENSE END -->')[1]
        dm = pre + block + post.lstrip('\n')
    else:
        dm = dm.rstrip('\n') + '\n\n' + block
    open(f'{P}/DATA.md', 'w').write(dm)
    print('\n'.join(st))


if __name__ == '__main__':
    main()
